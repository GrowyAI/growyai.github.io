#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate questions.js and qr-data.js from the two markdown question banks.

Sources of truth:
  questions.md          100 knowledge questions (L1-01 ... L5-20)
  questions-scenario.md 100 scenario questions (S1-01 ... S5-20)

The generated JS is what the browser loads, so the page also works from
file:// (no fetch, no build step, no server).
"""
import base64
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent

LEVELS = [
    {"id": 1, "age": "0–1 岁", "name": "第一关 · 0–1 岁"},
    {"id": 2, "age": "1–3 岁", "name": "第二关 · 1–3 岁"},
    {"id": 3, "age": "3–6 岁", "name": "第三关 · 3–6 岁"},
    {"id": 4, "age": "6–12 岁", "name": "第四关 · 6–12 岁"},
    {"id": 5, "age": "12–18 岁", "name": "第五关 · 12–18 岁"},
]

LETTERS = "ABC"


def clean(text):
    """Remove markdown emphasis/backticks that would show up literally in the UI."""
    return text.strip().replace("**", "").replace("`", "")


def parse_bank(path, prefix, source):
    """Parse one markdown bank. Both banks use A/B/C options; the rationale
    field is named 依据 in the knowledge bank and 解析 in the scenario bank."""
    md = path.read_text(encoding="utf-8")
    blocks = re.split(r"(?=^### " + prefix + r"[0-9]-[0-9]{2}｜)", md, flags=re.M)[1:]
    questions = []
    for block in blocks:
        head = re.match(
            r"^### " + prefix + r"([0-9])-([0-9]{2})｜([^｜\n]+)｜([^\n]+)", block
        )
        if not head:
            raise ValueError("Unrecognised question heading in {}: {}".format(path.name, block[:80]))

        level = int(head.group(1))
        qid = "{}{}-{}".format(prefix, level, head.group(2))
        topic = clean(head.group(3))
        tag = clean(head.group(4))

        stem_match = re.search(r"^\*\*题干\*\*：(.+)$", block, re.M)
        answer_match = re.search(r"^\*\*答案\*\*：([ABC])\s*$", block, re.M)
        rationale_match = re.search(r"^\*\*(?:依据|解析)\*\*：(.+)$", block, re.M)
        if not (stem_match and answer_match and rationale_match):
            raise ValueError("Incomplete question: " + qid)

        option_matches = re.findall(r"^- ([ABC])\. (.+)$", block, re.M)
        if [letter for letter, _ in option_matches] != list(LETTERS):
            raise ValueError("Options A-C incomplete for " + qid)

        questions.append({
            "id": qid,
            "level": level,
            "source": source,
            "topic": topic,
            "tag": tag,
            "stem": clean(stem_match.group(1)),
            "options": [clean(text) for _, text in option_matches],
            "answer": LETTERS.index(answer_match.group(1)),
            "rationale": clean(rationale_match.group(1)),
        })
    return questions


def write_js(path, assignment, payload):
    content = "/* Generated by build_data.py - do not edit by hand. */\n"
    content += assignment + " " + json.dumps(payload, ensure_ascii=False, indent=2) + ";\n"
    path.write_text(content, encoding="utf-8")


def validate(questions, source, expected_prefix):
    if len(questions) != 100:
        raise ValueError("{}: expected 100 questions, got {}".format(source, len(questions)))
    for level in LEVELS:
        count = sum(1 for q in questions if q["level"] == level["id"])
        if count != 20:
            raise ValueError("{} level {}: {} questions".format(source, level["id"], count))
    ids = [q["id"] for q in questions]
    expected = ["{}{}-{:02d}".format(expected_prefix, l, i) for l in range(1, 6) for i in range(1, 21)]
    if ids != expected:
        raise ValueError("{}: question ids are not contiguous".format(source))


def main():
    knowledge = parse_bank(ROOT / "questions.md", "L", "knowledge")
    scenario = parse_bank(ROOT / "questions-scenario.md", "S", "scenario")
    validate(knowledge, "knowledge", "L")
    validate(scenario, "scenario", "S")

    all_ids = [q["id"] for q in knowledge + scenario]
    if len(all_ids) != len(set(all_ids)):
        raise ValueError("Duplicate question ids across banks")

    write_js(ROOT / "questions.js", "window.QUESTION_BANK =", {
        "levels": LEVELS,
        "passScore": 8,
        "drawCount": 10,
        "drawPerSource": 5,
        "optionCount": 3,
        "letters": LETTERS,
        "questions": knowledge + scenario,
    })

    qr = {}
    for key, filename in (("site", "qr-site.png"), ("wechat", "qr-wechat.png")):
        raw = (ROOT / "assets" / filename).read_bytes()
        qr[key] = "data:image/png;base64," + base64.b64encode(raw).decode("ascii")
    write_js(ROOT / "qr-data.js", "window.QR_IMAGES =", qr)

    print("Generated questions.js: 200 questions (100 knowledge + 100 scenario), 5 levels x 20 each")
    print("Generated qr-data.js: {} QR images".format(len(qr)))


if __name__ == "__main__":
    main()
